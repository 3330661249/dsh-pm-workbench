import { mkdir, mkdtemp, readFile, symlink, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { describe, expect, test } from 'vitest'
import { assertArtifactsAbsent, inspectGeneratedArtifacts, REQUIRED_ARTIFACTS } from '../src/assertions/artifacts.js'
import { validateStrictDescriptors } from '../src/assertions/descriptors.js'
import { validateDirectGeneration } from '../src/assertions/generation.js'

const header = '/* Generated by @deepseek-ai/dsh-typert-generator from FaceModel — do not edit. */\n'

const emit = () => ({
  package: '@knight/dsh-typert-matrix-probe',
  packageRoot: 'packages/probe',
  face: 'host',
  exports: ['.'],
  js: `${header}export const TYPERT = {}\n`,
  dts: `${header}export declare const TYPERT: unknown\n`,
  remote: {
    js: `${header}export const TYPERT_REMOTE = {}\n`,
    dts: `${header}export declare const TYPERT_REMOTE: unknown\n`,
    dtsMap: JSON.stringify({
      version: 3,
      file: 'typert.remote-client.d.ts',
      sources: ['../src/index.ts'],
      names: [],
      mappings: '',
    }),
  },
})

const direct = () => ({
  discover: [{
    package: '@knight/dsh-typert-matrix-probe',
    root: 'packages/probe',
    faces: ['host'],
  }],
  automatic: [emit()],
  forced: [emit()],
})

describe('direct generator assertions', () => {
  test('requires one discovered host and identical non-empty automatic/forced output', () => {
    expect(validateDirectGeneration(direct())).toMatchObject({
      'lib/typert.host.js': expect.stringContaining('Generated by'),
      'lib/typert.remote-client.d.ts.map': expect.stringContaining('typert.remote-client'),
    })
  })

  test('rejects build-only false positives with empty generation', () => {
    const value = direct()
    value.automatic = []
    value.forced = []

    expect(() => validateDirectGeneration(value)).toThrow(/generation.*empty/i)
  })

  test('rejects automatic/forced disagreement and missing Remote strings', () => {
    const disagreement = direct()
    disagreement.forced[0]!.js += '// drift'
    const missingRemote = direct()
    missingRemote.automatic[0]!.remote!.dtsMap = ''

    expect(() => validateDirectGeneration(disagreement)).toThrow(/disagree/)
    expect(() => validateDirectGeneration(missingRemote)).toThrow(/non-empty Remote/)
  })
})

async function artifactFixture() {
  const probeRoot = await mkdtemp(path.join(os.tmpdir(), 'typert-artifacts-'))
  const expected = validateDirectGeneration(direct())
  const startedAtMs = Date.now() - 100
  for (const relative of REQUIRED_ARTIFACTS) {
    const absolute = path.join(probeRoot, relative)
    await mkdir(path.dirname(absolute), { recursive: true })
    await writeFile(absolute, expected[relative])
  }
  const manifest = {
    exports: {
      './typert': { types: './lib/typert.host.d.ts', default: './lib/typert.host.js' },
      './remote': { types: './lib/typert.remote-client.d.ts', default: './lib/typert.remote-client.js' },
    },
    files: [...REQUIRED_ARTIFACTS],
  }
  return { probeRoot, expected, startedAtMs, manifest }
}

describe('generated artifact assertions', () => {
  test('rejects pre-seeded generated output before any generator runs', async () => {
    const fixture = await artifactFixture()

    await expect(assertArtifactsAbsent(fixture.probeRoot)).rejects.toThrow(/present before generation/)
  })

  test('accepts five fresh regular files matching direct output and dry-pack inventory', async () => {
    const fixture = await artifactFixture()

    const evidence = await inspectGeneratedArtifacts({
      ...fixture,
      packFiles: [...REQUIRED_ARTIFACTS],
    })

    expect(evidence).toHaveLength(5)
    expect(evidence.every((entry) => /^[a-f0-9]{64}$/.test(entry.sha256))).toBe(true)
  })

  test('rejects a symlinked artifact and a source map with an absolute local path', async () => {
    const linked = await artifactFixture()
    const outside = path.join(linked.probeRoot, 'outside.js')
    await writeFile(outside, linked.expected['lib/typert.host.js'])
    const hostPath = path.join(linked.probeRoot, 'lib/typert.host.js')
    const original = await readFile(hostPath)
    await writeFile(hostPath, original)
    const { rm } = await import('node:fs/promises')
    await rm(hostPath)
    await symlink(outside, hostPath)
    await expect(inspectGeneratedArtifacts({ ...linked, packFiles: [...REQUIRED_ARTIFACTS] }))
      .rejects.toThrow(/symlink/)

    const badMap = await artifactFixture()
    await writeFile(
      path.join(badMap.probeRoot, 'lib/typert.remote-client.d.ts.map'),
      JSON.stringify({ version: 3, file: 'typert.remote-client.d.ts', sources: ['/Users/private/source.ts'] }),
    )
    badMap.expected['lib/typert.remote-client.d.ts.map'] = await readFile(
      path.join(badMap.probeRoot, 'lib/typert.remote-client.d.ts.map'),
      'utf8',
    )
    await expect(inspectGeneratedArtifacts({ ...badMap, packFiles: [...REQUIRED_ARTIFACTS] }))
      .rejects.toThrow(/absolute/)
  })

  test('rejects a missing pack file even when every build process exited zero', async () => {
    const fixture = await artifactFixture()

    await expect(inspectGeneratedArtifacts({
      ...fixture,
      packFiles: REQUIRED_ARTIFACTS.slice(0, -1),
    })).rejects.toThrow(/pack.*missing/i)
  })
})

function exactSchema(predicate: (value: unknown) => boolean) {
  return { safeParse: (value: unknown) => ({ success: predicate(value) }) }
}

const requestSchema = exactSchema((value) => {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false
  const record = value as Record<string, unknown>
  return Object.keys(record).length === 1 && record.nonce === 'matrix-v1'
})
const resultSchema = exactSchema((value) => {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false
  const record = value as Record<string, unknown>
  return Object.keys(record).length === 2 && record.ok === true && record.apiVersion === 'v1'
})

const invocation = () => ({
  id: 'matrixProbe/health',
  service: 'matrixProbe',
  namespace: 'matrixProbe',
  method: 'health',
  parameters: [{ codec: { mode: 'strict', typeSymbol: 'probe#MatrixHealthRequest', schema: requestSchema } }],
  result: { mode: 'strict', typeSymbol: 'probe#MatrixHealthResult', schema: resultSchema },
})

const modules = () => {
  const remoteContribution = {
    package: '@knight/dsh-typert-matrix-probe',
    descriptors: [invocation()],
  }
  return {
    host: {
      TYPERT: {
        package: '@knight/dsh-typert-matrix-probe',
        face: 'host',
        invocations: [invocation()],
      },
    },
    remote: { TYPERT_REMOTE: remoteContribution, default: remoteContribution },
  }
}

describe('strict descriptor assertions', () => {
  test('accepts only the exact method inventory and strict request/result codecs', () => {
    const value = modules()

    expect(validateStrictDescriptors(value.host, value.remote)).toEqual({
      methodIds: ['matrixProbe/health'],
      requestTypeSymbol: 'probe#MatrixHealthRequest',
      resultTypeSymbol: 'probe#MatrixHealthResult',
    })
  })

  test('rejects unexpected methods and permissive schemas', () => {
    const extra = modules()
    extra.host.TYPERT.invocations.push({ ...invocation(), id: 'matrixProbe/unknown', method: 'unknown' })
    const permissive = modules()
    permissive.remote.TYPERT_REMOTE.descriptors[0]!.parameters[0]!.codec.schema = exactSchema(() => true)

    expect(() => validateStrictDescriptors(extra.host, extra.remote)).toThrow(/exactly one/)
    expect(() => validateStrictDescriptors(permissive.host, permissive.remote)).toThrow(/malformed request/)
  })

  test('rejects codecs that strip or tolerate unknown object keys despite strict metadata', () => {
    const requestWide = modules()
    requestWide.host.TYPERT.invocations[0]!.parameters[0]!.codec.schema = exactSchema((value) => (
      typeof value === 'object'
      && value !== null
      && !Array.isArray(value)
      && (value as Record<string, unknown>).nonce === 'matrix-v1'
    ))
    const resultWide = modules()
    resultWide.remote.TYPERT_REMOTE.descriptors[0]!.result.schema = exactSchema((value) => (
      typeof value === 'object'
      && value !== null
      && !Array.isArray(value)
      && (value as Record<string, unknown>).ok === true
      && (value as Record<string, unknown>).apiVersion === 'v1'
    ))

    expect(() => validateStrictDescriptors(requestWide.host, requestWide.remote)).toThrow(/malformed request/)
    expect(() => validateStrictDescriptors(resultWide.host, resultWide.remote)).toThrow(/malformed result/)
  })

  test('rejects Remote default/named identity drift and Host/Remote id mismatch', () => {
    const identity = modules()
    identity.remote.default = { ...identity.remote.TYPERT_REMOTE }
    const mismatch = modules()
    mismatch.remote.TYPERT_REMOTE.descriptors[0]!.id = 'different/health'

    expect(() => validateStrictDescriptors(identity.host, identity.remote)).toThrow(/object identity/)
    expect(() => validateStrictDescriptors(mismatch.host, mismatch.remote)).toThrow(/matrixProbe\/health|agree/)
  })
})
